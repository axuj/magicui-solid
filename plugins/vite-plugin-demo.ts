import type { Plugin, ResolvedConfig } from 'vite'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { cwd } from 'node:process'

export default function demoTypesPlugin(): Plugin {
  const demosDir = join(cwd(), 'src/demos')
  const generatedDir = join(demosDir, '__generated__')
  const outputFile = join(generatedDir, 'demos.ts')
  const demosDirNormalized = demosDir.replace(/\\/g, '/')

  let lastContent = ''

  function generateContent(): string {
    if (!existsSync(demosDir))
      return lastContent

    const files = readdirSync(demosDir).filter(
      f => f.endsWith('.tsx') && !f.startsWith('_'),
    )
    if (files.length === 0)
      return lastContent

    const names = files.map(f => f.replace(/\.tsx$/, ''))

    const rawImportLines = names.map(n => `import _${n} from '@/demos/${n}.tsx?raw'`).join('\n')
    const compImportLines = names.map(n => `import { ${n} } from '@/demos/${n}'`).join('\n')

    return `// @ts-nocheck
// Generated by vite-plugin-demo — do not edit manually
${rawImportLines}

${compImportLines}

export const demoPaths = {
${names.map(n => `  ${n}: '/src/demos/${n}.tsx'`).join(',\n')},
} as const

export const demoRawMap = {
${names.map(n => `  ${n}: _${n}`).join(',\n')},
} as const

export const demoComponentMap = {
${names.map(n => `  ${n}`).join(',\n')},
} as const
`
  }

  function scanAndGenerate() {
    const content = generateContent()
    if (content === lastContent)
      return
    if (!existsSync(generatedDir))
      mkdirSync(generatedDir, { recursive: true })
    writeFileSync(outputFile, content, 'utf-8')
    lastContent = content
  }

  return {
    name: 'vite-plugin-demo',
    configResolved(_config: ResolvedConfig) {
      if (existsSync(outputFile))
        lastContent = readFileSync(outputFile, 'utf-8')

      scanAndGenerate()
    },
    watchChange(id: string) {
      if (id.replace(/\\/g, '/').startsWith(demosDirNormalized)) {
        scanAndGenerate()
      }
    },
  }
}
